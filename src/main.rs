//! Stage 1 of the Two-Instance Spike: Window and OpenGL 3.3 Core Context.
//!
//! What this program does:
//! 1. Prints the runtime `libprojectM` version (verifying our DLL link stays intact).
//! 2. Opens one 800x600 window using `winit` + `glutin` with an OpenGL 3.3 Core context.
//! 3. Loads OpenGL functions via `glow` (using Windows `wglGetProcAddress` through `glutin`).
//! 4. Prints `GL_VENDOR`, `GL_RENDERER`, and `GL_VERSION` and warns if the active GPU
//!    is not the NVIDIA Quadro RTX 3000.
//! 5. Draws a smooth breathing dark-teal background at VSync and checks `glGetError()`
//!    on every single frame, logging results to `logs/gl_errors.log`.
//! 6. Press `Esc` or click the window's Close (`X`) button to exit cleanly.

mod gl_log;

use std::ffi::CStr;
use std::num::NonZeroU32;
use std::time::Instant;

use glow::HasContext;
use glutin::config::ConfigTemplateBuilder;
use glutin::context::{
    ContextApi, ContextAttributesBuilder, PossiblyCurrentContext, Version,
};
use glutin::display::GetGlDisplay;
use glutin::prelude::*;
use glutin::surface::{Surface, SwapInterval, WindowSurface};
use glutin_winit::{DisplayBuilder, GlWindow};
use raw_window_handle::HasWindowHandle;
use winit::application::ApplicationHandler;
use winit::dpi::LogicalSize;
use winit::event::{ElementState, KeyEvent, WindowEvent};
use winit::event_loop::{ActiveEventLoop, ControlFlow, EventLoop};
use winit::keyboard::{Key, NamedKey};
use winit::window::{Window, WindowId};

use crate::gl_log::GlErrorLogger;

/// Raw C bindings generated by `build.rs` from `projectM-4/projectM.h`.
mod ffi {
    #![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, dead_code)]
    include!(concat!(env!("OUT_DIR"), "/projectm_bindings.rs"));
}

/// Reads the runtime `libprojectM` version string and frees the C allocation safely.
fn get_projectm_version_string() -> String {
    unsafe {
        let raw_ptr = ffi::projectm_get_version_string();
        assert!(!raw_ptr.is_null(), "projectm_get_version_string returned null");
        let version = CStr::from_ptr(raw_ptr).to_string_lossy().into_owned();
        ffi::projectm_free_string(raw_ptr);
        version
    }
}

/// Holds the active window, OpenGL context, surface, and function loader once created.
///
/// Rust concept: Storing GPU resources together inside a struct makes their lifetime
/// explicit. When `GlState` is dropped on exit, the OpenGL surface and context are
/// cleaned up automatically in field order.
struct GlState {
    window: Window,
    gl_surface: Surface<WindowSurface>,
    gl_context: PossiblyCurrentContext,
    gl: glow::Context,
    start_time: Instant,
    last_report_time: Instant,
    last_report_frames: u64,
    frame_count: u64,
}

/// Top-level application state passed to `winit`'s `EventLoop`.
///
/// Rust concept: `Option<GlState>` means "either `None` (window not created yet)
/// or `Some(state)` (window is open)". Rust uses `Option` instead of Python's `None`
/// so the compiler forces you to check whether the window exists before using it.
struct Stage1App {
    state: Option<GlState>,
    logger: GlErrorLogger,
}

impl Stage1App {
    fn new(logger: GlErrorLogger) -> Self {
        Self {
            state: None,
            logger,
        }
    }

    /// Creates the window, requests an OpenGL 3.3 Core context, loads GL functions,
    /// and prints GPU identification strings.
    fn init_window_and_gl(&mut self, event_loop: &ActiveEventLoop) {
        let window_attrs = Window::default_attributes()
            .with_title("MilkDrop VJ — Stage 1 OpenGL Check (Esc to close)")
            .with_inner_size(LogicalSize::new(800.0, 600.0));

        // Ask glutin for a standard 8-bit-per-channel RGBA framebuffer with double buffering.
        let template = ConfigTemplateBuilder::new().with_alpha_size(8);

        let display_builder = DisplayBuilder::new().with_window_attributes(Some(window_attrs));

        // Pick the best matching pixel format configuration (preferring the most color bits).
        let (window, gl_config) = display_builder
            .build(event_loop, template, |configs| {
                configs
                    .reduce(|accum, config| {
                        if config.num_samples() < accum.num_samples() {
                            config
                        } else {
                            accum
                        }
                    })
                    .expect("No compatible OpenGL pixel format found")
            })
            .expect("Failed to create winit window and glutin GL display");

        let window = window.expect("DisplayBuilder did not return a window");
        let raw_window_handle = window
            .window_handle()
            .expect("Failed to obtain native window handle")
            .as_raw();

        let gl_display = gl_config.display();

        // Request OpenGL 3.3 Core Profile:
        // - Matches libprojectM 4.1.8's shader target (#version 330 core).
        // - Matches egui_glow's OpenGL 3.3 Core requirement for Milestone 2.
        let context_attributes = ContextAttributesBuilder::new()
            .with_context_api(ContextApi::OpenGl(Some(Version::new(3, 3))))
            .build(Some(raw_window_handle));

        let not_current_context = unsafe {
            gl_display
                .create_context(&gl_config, &context_attributes)
                .expect("Failed to create OpenGL 3.3 Core context")
        };

        let surface_attrs = window
            .build_surface_attributes(Default::default())
            .expect("Failed to build window surface attributes");

        let gl_surface = unsafe {
            gl_display
                .create_window_surface(&gl_config, &surface_attrs)
                .expect("Failed to create OpenGL window surface")
        };

        // Make the OpenGL context current on this thread before loading any GL functions.
        let gl_context = not_current_context
            .make_current(&gl_surface)
            .expect("Failed to make OpenGL context current");

        // Enable VSync (1 swap interval = lock frame pacing to monitor refresh rate).
        if let Err(err) =
            gl_surface.set_swap_interval(&gl_context, SwapInterval::Wait(NonZeroU32::new(1).unwrap()))
        {
            eprintln!("Warning: Could not enable VSync: {err}");
            self.logger.log_info(&format!("Warning: VSync failed: {err}"));
        }

        // Load OpenGL 3.3+ function pointers at runtime via glutin's `get_proc_address`
        // (on Windows, this calls `wglGetProcAddress` under the hood).
        let gl = unsafe {
            glow::Context::from_loader_function_cstr(|symbol: &CStr| {
                gl_display.get_proc_address(symbol) as *const _
            })
        };

        // Query and print GPU vendor, renderer, and OpenGL version strings.
        let vendor = unsafe { gl.get_parameter_string(glow::VENDOR) };
        let renderer = unsafe { gl.get_parameter_string(glow::RENDERER) };
        let version = unsafe { gl.get_parameter_string(glow::VERSION) };

        println!("=== OpenGL Context Ready (Requested: OpenGL 3.3 Core) ===");
        println!("GL_VENDOR:   {vendor}");
        println!("GL_RENDERER: {renderer}");
        println!("GL_VERSION:  {version}");

        self.logger.log_info(&format!("GL_VENDOR={vendor}"));
        self.logger.log_info(&format!("GL_RENDERER={renderer}"));
        self.logger.log_info(&format!("GL_VERSION={version}"));

        // Warn clearly if Windows did not select the NVIDIA Quadro RTX 3000.
        // Note: NVIDIA puts "NVIDIA Corporation" in GL_VENDOR and "Quadro RTX 3000/..." in GL_RENDERER.
        let is_nvidia = vendor.to_ascii_lowercase().contains("nvidia")
            || renderer.to_ascii_lowercase().contains("nvidia");
        let is_rtx_3000 = renderer.to_ascii_lowercase().contains("rtx 3000");

        if !(is_nvidia && is_rtx_3000) {
            let warn = format!(
                "WARNING: Active GPU is `{vendor}` / `{renderer}`, NOT NVIDIA Quadro RTX 3000! \
                 Do not change BIOS or Windows settings automatically — report this first."
            );
            eprintln!("{warn}");
            self.logger.log_info(&warn);
        } else {
            println!("GPU Check: Confirmed NVIDIA Quadro RTX 3000 is rendering.");
            self.logger
                .log_info("GPU Check: Confirmed NVIDIA Quadro RTX 3000 is rendering.");
        }

        // Check for any OpenGL errors right after initialization.
        self.logger.check_frame(&gl, 0, "main-init");

        // Explicitly show and focus the window.
        // Why: When a child process is launched from a hidden background terminal on Windows,
        // winit's initial `SW_SHOWDEFAULT` can inherit `SW_HIDE` from the parent shell.
        // Calling `set_visible(true)` and `focus_window()` sends `SW_SHOW` explicitly.
        window.set_visible(true);
        window.focus_window();

        // Set the initial OpenGL drawing area to match the window size.
        let size = window.inner_size();
        let pos = window.outer_position().ok();
        println!(
            "Window ready: size={}x{}, visible={:?}, pos={:?}",
            size.width,
            size.height,
            window.is_visible(),
            pos
        );
        self.logger.log_info(&format!(
            "Window ready: size={}x{}, visible={:?}, pos={:?}",
            size.width,
            size.height,
            window.is_visible(),
            pos
        ));

        unsafe {
            gl.viewport(0, 0, size.width as i32, size.height as i32);
        }

        let now = Instant::now();
        self.state = Some(GlState {
            window,
            gl_surface,
            gl_context,
            gl,
            start_time: now,
            last_report_time: now,
            last_report_frames: 0,
            frame_count: 0,
        });
    }

    /// Renders one frame: a gentle breathing dark-teal color so you can visually
    /// confirm smooth VSync rendering, followed by a per-frame `glGetError()` check.
    fn render_frame(&mut self) {
        let Some(state) = self.state.as_mut() else {
            return;
        };

        state.frame_count += 1;
        let elapsed = state.start_time.elapsed().as_secs_f32();

        // Smoothly pulse brightness between dark navy and teal (~0.5 Hz).
        let pulse = 0.5 + 0.5 * (elapsed * 2.0).sin();
        let r = 0.04;
        let g = 0.12 + 0.18 * pulse;
        let b = 0.22 + 0.22 * pulse;

        unsafe {
            state.gl.clear_color(r, g, b, 1.0);
            state.gl.clear(glow::COLOR_BUFFER_BIT);
        }

        // Check OpenGL errors every single frame and log them if any occur.
        self.logger
            .check_frame(&state.gl, state.frame_count, "main-frame");

        state
            .gl_surface
            .swap_buffers(&state.gl_context)
            .expect("Failed to swap OpenGL buffers");

        // Print a 1-second heartbeat so we can verify continuous rendering in the console.
        let since_report = state.last_report_time.elapsed().as_secs_f64();
        if state.frame_count == 1 {
            println!("First frame rendered and swapped.");
        } else if since_report >= 1.0 {
            let delta_frames = state.frame_count - state.last_report_frames;
            let fps = delta_frames as f64 / since_report;
            println!(
                "[Stage 1] frames={}, fps={:.1}, gl_errors={}",
                state.frame_count,
                fps,
                self.logger.total_errors()
            );
            state.last_report_time = Instant::now();
            state.last_report_frames = state.frame_count;
        }

        // Ask winit to render the next frame continuously.
        state.window.request_redraw();
    }

    /// Writes a final summary when the window closes.
    fn log_shutdown(&mut self) {
        if let Some(state) = &self.state {
            let secs = state.start_time.elapsed().as_secs_f64();
            let avg_fps = if secs > 0.0 {
                state.frame_count as f64 / secs
            } else {
                0.0
            };
            let summary = format!(
                "Stage 1 closed cleanly after {} frames in {:.2}s (avg {:.1} FPS). Total GL errors: {}",
                state.frame_count,
                secs,
                avg_fps,
                self.logger.total_errors()
            );
            println!("{summary}");
            println!("GL error log saved to: {}", self.logger.path().display());
            self.logger.log_info(&summary);
        }
    }
}

/// Rust concept: A `trait` is like a Python abstract base class or interface.
/// Implementing `ApplicationHandler` tells `winit` how to call our app when
/// the window starts, resizes, receives key presses, or needs a redraw.
impl ApplicationHandler for Stage1App {
    fn resumed(&mut self, event_loop: &ActiveEventLoop) {
        if self.state.is_none() {
            self.init_window_and_gl(event_loop);
            if let Some(state) = &self.state {
                state.window.request_redraw();
            }
        }
    }

    fn window_event(
        &mut self,
        event_loop: &ActiveEventLoop,
        _window_id: WindowId,
        event: WindowEvent,
    ) {
        match event {
            WindowEvent::CloseRequested => {
                self.log_shutdown();
                event_loop.exit();
            }
            WindowEvent::KeyboardInput {
                event:
                    KeyEvent {
                        logical_key: Key::Named(NamedKey::Escape),
                        state: ElementState::Pressed,
                        ..
                    },
                ..
            } => {
                self.log_shutdown();
                event_loop.exit();
            }
            WindowEvent::Resized(new_size) => {
                if let Some(state) = &self.state {
                    if let (Some(w), Some(h)) = (
                        NonZeroU32::new(new_size.width),
                        NonZeroU32::new(new_size.height),
                    ) {
                        state.gl_surface.resize(&state.gl_context, w, h);
                        unsafe {
                            state
                                .gl
                                .viewport(0, 0, new_size.width as i32, new_size.height as i32);
                        }
                    }
                }
            }
            WindowEvent::RedrawRequested => {
                self.render_frame();
            }
            _ => {}
        }
    }
}

fn main() {
    let pm_version = get_projectm_version_string();
    println!("libprojectM runtime version: {pm_version}");
    println!("Opening Stage 1 OpenGL window... Press Esc or click X to close.");

    let logger = GlErrorLogger::open("logs/gl_errors.log")
        .expect("Could not initialize OpenGL error log file");

    let event_loop = EventLoop::new().expect("Failed to create winit event loop");
    event_loop.set_control_flow(ControlFlow::Poll);

    let mut app = Stage1App::new(logger);
    event_loop
        .run_app(&mut app)
        .expect("Event loop exited with an error");
}
